class NoDialog:
    def choose(self, initial_path=None):
        raise RuntimeError("API tests never open a native picker")
    def close(self):
        pass


def tree_digest(root: Path) -> dict[str, str]:
    return {path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in root.rglob("*") if path.is_file()}


class PreparationAPITests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="preparation 中文 space ")
        self.root = Path(self.temp.name)
        self.paths = make_suite(self.root / "synthetic inputs")
        self.server = create_server(self.root / "工作区 workspace", port=0, directory_picker=NoDialog())
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.host = f"127.0.0.1:{self.server.server_port}"
        self.token = self.request("GET", "/api/state")[1]["csrf_token"]
        self.assets = {}

    def tearDown(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=5)
        self.temp.cleanup()

    def request(self, method, path, payload=None, *, token=True, headers=None):
        conn = http.client.HTTPConnection("127.0.0.1", self.server.server_port, timeout=10)
        body = None
        send = {"Host": self.host}
        if payload is not None:
            body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            send["Content-Type"] = "application/json; charset=utf-8"
        if method == "POST" and token:
            send["X-Workbench-Token"] = self.token
        send.update(headers or {})
        try:
            conn.request(method, path, body=body, headers=send)
            response = conn.getresponse()
            status = response.status
            raw = response.read()
            content_type = response.getheader("Content-Type", "")
        finally:
            conn.close()
        return status, json.loads(raw.decode("utf-8")) if content_type.startswith("application/json") else raw

    def import_case(self, key, source_kind="simulation"):
        if key not in self.assets:
            status, value = self.request("POST", "/api/assets/import", {
                "path": str(self.paths[key]), "name": "SYNTHETIC " + key,
                "source_kind": source_kind, "_synthetic": True,
                "task": TASK, "embodiment": "SYNTHETIC_28D", "tags": ["synthetic", "仅软件验收"],
                "license": "CC0-1.0 generated test fixture",
                "source_reference": "generated by tests/preparation_fixtures.py",
            })
            self.assertEqual(status, 200, value)
            self.assertTrue(value["synthetic"])
            self.assets[key] = value
        return self.assets[key]

    def episodes(self, **query):
        suffix = "?" + urlencode(query) if query else ""
        status, value = self.request("GET", "/api/episodes" + suffix)
        self.assertEqual(status, 200, value)
        return value["episodes"]

    def episode(self, key, source_kind="simulation"):
        asset = self.import_case(key, source_kind)
        rows = self.episodes(asset_id=asset["id"])
        self.assertEqual(len(rows), 1, rows)
        return rows[0]

    def draft(self, items, *, split=None, sampling=None, **fields):
        payload = {"name": "SYNTHETIC 数据准备验收", "items": items,
                   "split": split or {"train": 100, "validation": 0, "test": 0, "seed": 42},
                   "sampling": sampling or {"mode": "natural"}, **fields}
        status, value = self.request("POST", "/api/datasets/draft", payload)
        self.assertEqual(status, 200, value)
        return value

    def confirm(self, dataset):
        status, value = self.request("POST", f"/api/datasets/{dataset['id']}/confirm", {"revision": dataset["revision"]})
        self.assertEqual(status, 200, value)
        self.assertEqual(value["status"], "confirmed")
        return value

    def build(self, dataset):
        status, value = self.request("POST", f"/api/datasets/{dataset['id']}/build", {})
        self.assertEqual(status, 200, value)
        self.assertEqual(value["stage"], "prepare")
        return value

    def wait_job(self, job, timeout=15):
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            status, detail = self.request("GET", "/api/jobs/" + job["id"])
            self.assertEqual(status, 200, detail)
            if detail["job"]["status"] not in {"queued", "running", "cancelling"}:
                return detail
            time.sleep(.025)
        self.fail("lightweight preparation worker did not finish within timeout")

    def archive(self, detail):
        self.assertEqual(detail["job"]["status"], "succeeded", detail)
        files = detail["result"]["artifacts"]
        artifact = next((f for f in files if f["name"].endswith(".zip")), None)
        self.assertIsNotNone(artifact, files)
        status, raw = self.request("GET", artifact["url"])
        self.assertEqual(status, 200)
        self.assertIsInstance(raw, bytes)
        return zipfile.ZipFile(io.BytesIO(raw))

    @staticmethod
    def read_records(archive):
        return [json.loads(row) for row in archive.read("records.jsonl").decode("utf-8").splitlines() if row]

