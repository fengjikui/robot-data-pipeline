    def test_cancelled_build_can_be_retried_without_new_confirmation(self):
        a = self.episode("source_a")
        dataset = self.confirm(self.draft([{"episode_id": a["id"], "start_frame": 0, "end_frame": 5}]))
        original_popen = subprocess.Popen
        started = threading.Event()
        def owned_sleep_process(argv, **kwargs):
            process = original_popen([sys.executable, "-c", "import time; time.sleep(30)"], **kwargs)
            started.set()
            return process
        with patch("robot_pipeline.workbench.service.subprocess.Popen", side_effect=owned_sleep_process):
            job = self.build(dataset)
            self.assertTrue(started.wait(3), "managed preparation worker did not start")
            status, _ = self.request("POST", f"/api/jobs/{job['id']}/cancel", {})
            self.assertEqual(status, 200)
            detail = self.wait_job(job)
            self.assertEqual(detail["job"]["status"], "cancelled", detail)
        self.assertEqual(self.request("GET", f"/api/datasets/{dataset['id']}")[1], dataset)
        retried = self.build(dataset)
        self.assertNotEqual(retried["id"], job["id"])
        self.assertEqual(self.wait_job(retried)["job"]["status"], "succeeded")

    def test_failed_worker_keeps_input_and_allows_real_retry(self):
        a = self.episode("source_a")
        dataset = self.confirm(self.draft([{"episode_id": a["id"], "start_frame": 0, "end_frame": 5}]))
        original_popen = subprocess.Popen
        def owned_failure_process(argv, **kwargs):
            return original_popen([sys.executable, "-c", "import sys; print('SYNTHETIC injected prepare failure'); sys.exit(9)"], **kwargs)
        with patch("robot_pipeline.workbench.service.subprocess.Popen", side_effect=owned_failure_process):
            failed = self.wait_job(self.build(dataset))
