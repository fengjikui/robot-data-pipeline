        self.assertEqual(status, 409)
        self.import_case("source_b")
        self.assertEqual(self.request("GET", f"/api/datasets/{confirmed['id']}")[1], confirmed)
        child = self.draft(items, parent_id=confirmed["id"], name="SYNTHETIC V2")
        self.assertNotEqual(child["id"], confirmed["id"])
        self.assertEqual(self.request("GET", f"/api/datasets/{confirmed['id']}")[1], confirmed)

