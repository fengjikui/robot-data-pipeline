    def test_draft_revision_conflict_and_confirmed_version_are_immutable(self):
        a = self.episode("source_a")
        items = [{"episode_id": a["id"], "start_frame": 1, "end_frame": 6}]
        draft = self.draft(items)
        before = self.request("GET", f"/api/datasets/{draft['id']}")[1]
